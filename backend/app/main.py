"""FastAPI application factory."""

from __future__ import annotations

import logging

from fastapi import APIRouter, Depends, FastAPI
from fastapi.middleware.cors import CORSMiddleware

from app import __version__
from app.config import Settings
from app.db import make_engine, make_session_factory
from app.embeddings import build_embedder
from app.llm import LLMProvider, build_llm
from app.rag import RagPipeline
from app.routers import chat, documents, workspaces
from app.schemas import HealthOut
from app.security import RateLimiter, require_api_key
from app.vectorstore import ChromaVectorStore, InMemoryVectorStore, VectorStore

logger = logging.getLogger("docmind")

DESCRIPTION = """\
**DocMind** lets you upload documents into workspaces and ask questions about them.
Answers are generated by the LLM of your choice (OpenAI, Anthropic Claude, Gemini, or an
offline fake model) and cite the exact chunks and pages they came from.

Authenticate with the `X-API-Key` header (click **Authorize**).
"""


def create_app(
    settings: Settings | None = None,
    *,
    llm: LLMProvider | None = None,
    store: VectorStore | None = None,
) -> FastAPI:
    settings = settings or Settings()
    logging.basicConfig(level=logging.INFO, format="%(levelname)s %(name)s: %(message)s")

    app = FastAPI(
        title="DocMind API",
        version=__version__,
        description=DESCRIPTION,
        docs_url="/api/docs",
        redoc_url="/api/redoc",
        openapi_url="/api/openapi.json",
    )

    engine = make_engine(settings.database_url)
    if store is None:
        store = (
            InMemoryVectorStore()
            if settings.vector_store == "memory"
            else ChromaVectorStore(settings.chroma_path)
        )
    app.state.settings = settings
    app.state.engine = engine
    app.state.session_factory = make_session_factory(engine)
    app.state.pipeline = RagPipeline(
        embedder=build_embedder(settings),
        store=store,
        chunk_size=settings.chunk_size,
        chunk_overlap=settings.chunk_overlap,
    )
    app.state.llm = llm or build_llm(settings)
    app.state.rate_limiter = RateLimiter(settings.rate_limit_per_minute)

    if not settings.api_key_set:
        logger.warning("API_KEYS is empty: authentication is DISABLED (local development only)")

    app.add_middleware(
        CORSMiddleware,
        allow_origins=settings.cors_origin_list,
        allow_methods=["*"],
        allow_headers=["*"],
    )

    @app.get("/api/health", response_model=HealthOut, tags=["meta"], summary="Health check")
    def health() -> HealthOut:
        return HealthOut(
            status="ok",
            version=__version__,
            llm_provider=app.state.llm.name,
            embedding_provider=app.state.pipeline.embedder.slug,
            vector_store=settings.vector_store,
            auth_enabled=bool(settings.api_key_set),
        )

    api = APIRouter(prefix="/api", dependencies=[Depends(require_api_key)])
    api.include_router(workspaces.router)
    api.include_router(documents.router)
    api.include_router(chat.router)
    app.include_router(api)
    return app


def get_app() -> FastAPI:
    """Entry point for ``uvicorn app.main:get_app --factory``."""
    return create_app()
